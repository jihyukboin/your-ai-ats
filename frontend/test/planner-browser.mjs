// Run against a local verification backend with backend/scripts/verify_submission.py --serve.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.PLANNER_UI_URL || 'http://127.0.0.1:5173'
const dir = fileURLToPath(new URL('../../docs/evidence/', import.meta.url))
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 950 }, locale: 'ko-KR' })
  page.setDefaultTimeout(10000)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  const button = (name) => page.getByRole('button', { name, exact: true })
  const input = page.getByRole('textbox', { name: '플래너에게 요청' })
  async function send(message) {
    await input.fill(message)
    const response = page.waitForResponse(r => r.url().endsWith('/api/planner/chat') && r.request().method() === 'POST')
    await button('보내기').click()
    const result = await response
    assert.equal(result.status(), 200)
    await page.getByText('요청 처리 중', { exact: false }).waitFor({ state: 'hidden' })
    return result.json()
  }
  await page.goto(base)
  await page.getByRole('link', { name: /포트폴리오 준비 플래너/ }).click()
  await input.waitFor()
  // Hold delivery of the first real request so the pending state can be captured deterministically.
  let release
  const gate = new Promise(resolve => { release = resolve })
  await page.route('**/api/planner/chat', async route => { await gate; await route.continue() }, { times: 1 })
  const sending = send('2026-11-18 14:00부터 14:10까지 Python 이슈 읽기 계획을 짜줘')
  await page.getByRole('status').filter({ hasText: '요청 처리 중' }).waitFor()
  await page.screenshot({ path: dir + 'pending.png' })
  release()
  const result = await sending
  assert.equal(result.replans, 1)
  await page.screenshot({ path: dir + 'chat.png', fullPage: true })
  await page.locator('summary').filter({ hasText: '실행 과정' }).first().click()
  const mark = page.locator('summary').filter({ hasText: /재계획/ }).first()
  await mark.scrollIntoViewIfNeeded()
  await page.screenshot({ path: dir + 'replan.png' })
  await button('계획 저장').click()
  await page.getByText('계획을 저장했습니다.', { exact: true }).waitFor()
  const again = await send('2026-11-18 14:00부터 14:10까지 Python 이슈 읽기 계획을 짜줘')
  assert.equal(again.status, 'recommended')
  await button('계획 저장').last().click()
  await page.getByText(/저장했습니다. 시간이 겹치는 계획/).waitFor()
  await button('저장한 계획').click()
  await button('수정').first().waitFor()
  assert.equal(await page.locator('article').filter({ has: button('수정') }).count(), 2)
  await button('수정').first().click()
  await page.getByLabel('제목', { exact: true }).fill('포트폴리오 메모 정리')
  await button('변경 저장').click()
  await page.getByRole('heading', { name: '포트폴리오 메모 정리' }).waitFor()
  await page.screenshot({ path: dir + 'plans.png' })
  await button('삭제').first().click()
  await page.getByText('계획을 삭제했습니다.').waitFor()
  assert.equal(await button('수정').count(), 1)
  await button('실행 로그').click()
  await page.getByRole('button', { name: new RegExp(result.session_id) }).click()
  await page.getByRole('heading', { name: '2026-11-18 14:00부터 14:10까지 Python 이슈 읽기 계획을 짜줘' }).first().waitFor()
  await page.screenshot({ path: dir + 'logs.png' })
  await page.reload()
  await page.getByText('GitHub 이슈 열기', { exact: true }).first().waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await button('새 대화').click()
  await send('2026-11-18 14:00부터 15:00까지 Python 이슈 읽기 계획을 짜줘. 참고자료도 알려줘')
  await page.screenshot({ path: dir + 'partial-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1200, height: 950 })
  await button('새 대화').click()
  const cap = await send('2026-11-18 14:00부터 14:02까지 Python 이슈 읽기 계획을 짜줘')
  assert.equal(cap.status, 'no_match')
  await page.screenshot({ path: dir + 'limit.png', fullPage: true })
  await button('실행 로그').click()
  const log = page.locator('article').filter({ has: page.getByRole('button', { name: new RegExp(cap.session_id) }) })
  await log.getByRole('button', { name: '로그 삭제' }).click()
  await log.waitFor({ state: 'detached' })
  await button('대화').click()
  await button('새 대화').click()
  await send('어떻게 하지?')
  await page.getByText(/모델 API 키가 없어/).first().waitFor()
  await page.screenshot({ path: dir + 'missing-key.png' })
  await page.goto(base + '/api/planner/tools')
  assert((await page.locator('body').innerText()).includes('candidate_detail'))
  // Format the live endpoint response for a legible capture on headless Chromium.
  await page.evaluate(() => {
    const output = document.querySelector('pre')
    if (output) output.textContent = JSON.stringify(JSON.parse(output.textContent), null, 2)
  })
  await page.screenshot({ path: dir + 'tools.png' })
  assert.deepEqual(errors, [])
  console.log('브라우저 확인 완료 · 진입, 대화, 재계획, 저장·겹침, 수정·삭제, 로그, 새로고침, 모바일')
} finally {
  await browser.close()
}
